-- Plans and MoMo payments. Never edit after merge: add V4__... instead.
CREATE TABLE subscription (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL,
    plan       VARCHAR(20)   NOT NULL,
    started_at TIMESTAMP(6)  NOT NULL,
    expires_at TIMESTAMP(6),
    CONSTRAINT uk_subscription_user UNIQUE (user_id),
    CONSTRAINT fk_subscription_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);

CREATE TABLE payment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL,
    order_id      VARCHAR(64)   NOT NULL,
    request_id    VARCHAR(64)   NOT NULL,
    plan          VARCHAR(20)   NOT NULL,
    amount        BIGINT        NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    momo_trans_id BIGINT,
    result_code   INTEGER,
    message       VARCHAR(255),
    created_at    TIMESTAMP(6)  NOT NULL,
    paid_at       TIMESTAMP(6),
    CONSTRAINT uk_payment_order UNIQUE (order_id),
    CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_payment_user_created ON payment (user_id, created_at);
